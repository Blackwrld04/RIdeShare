export function getRidesForState(
  stateName: string = 'Lagos',
  query?: { origin?: string; dest?: string }
): RideOffer[] {
  const normState = (stateName || 'Lagos').trim().toLowerCase();

  // If user explicitly searches for an interstate route
  const from = (query?.origin || '').trim().toLowerCase();
  const to = (query?.dest || '').trim().toLowerCase();

  if (from || to) {
    const combinedMatches = ALL_DEMO_RIDES.filter((r) => {
      const matchO = !from || r.originTitle.toLowerCase().includes(from) || r.originLandmark.toLowerCase().includes(from);
      const matchD = !to || r.destTitle.toLowerCase().includes(to) || r.destLandmark.toLowerCase().includes(to);
      return matchO && matchD;
    });

    if (combinedMatches.length > 0) {
      return combinedMatches;
    }
  }

  // State-specific keywords for matching
  const stateKeywordsMap: Record<string, string[]> = {
    osun: ['osun', 'osogbo', 'ile-ife', 'ife', 'ede', 'ilesa', 'ikirun', 'iwo', 'gbongan', 'abere'],
    lagos: ['lagos', 'berger', 'lekki', 'victoria island', 'ikeja', 'ikorodu', 'ajah', 'yaba', 'cms', 'marina', 'maryland'],
    'fct abuja': ['abuja', 'fct', 'gwarinpa', 'kubwa', 'wuse', 'central business district', 'cbd', 'lugbe', 'maitama', 'garki'],
    abuja: ['abuja', 'fct', 'gwarinpa', 'kubwa', 'wuse', 'central business district', 'cbd', 'lugbe', 'maitama', 'garki'],
    oyo: ['oyo', 'ibadan', 'iwo road', 'challenge', 'dugbe', 'ogbomoso'],
    rivers: ['rivers', 'port harcourt', 'waterlines', 'eleme', 'choba', 'aba road'],
    edo: ['edo', 'benin', 'ring road', 'auchi', 'ekpoma'],
    anambra: ['anambra', 'onitsha', 'awka', 'nnewi', 'upper iweka'],
    enugu: ['enugu', 'holy ghost', 'nsukka', '9th mile'],
    kano: ['kano', 'kofar ruwa', 'sabon gari', 'zaria'],
    kaduna: ['kaduna', 'command junction', 'kawo', 'zaria'],
    delta: ['delta', 'asaba', 'warri', 'ughelli', 'summit'],
    ogun: ['ogun', 'abeokuta', 'sagamu', 'mowe', 'ijebu'],
  };

  if (normState === 'osun') {
    return OSUN_DEMO_RIDES;
  }

  const keywords = stateKeywordsMap[normState] || [normState];

  const matchedRides = ALL_DEMO_RIDES.filter((r) => {
    const text = `${r.originTitle} ${r.originLandmark} ${r.destTitle} ${r.destLandmark}`.toLowerCase();
    return keywords.some((k) => text.includes(k));
  });

  if (matchedRides.length > 0) {
    return matchedRides;
  }

  return generateRidesForState(stateName);
}


